"""answers/*.txt -> ../answers.js  (run: python quantum/answers/build.py)

A file is sections headed "=== <question tag>" (tags match PYQ in index.html).
Prose is plain HTML. Code goes in fenced blocks:
  ```<anything>   shown as a code/maths block (```gbox: a monospace maths block)
  ```out  with @@OUT name@@                       real captured output from out/name.txt
A section whose whole body is "@@SAME <tag>" reuses that tag's answer.
"""
import glob, html, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))


def block(m):
    kind, body = m.group(1).strip(), m.group(2)
    if kind == "out":
        body = re.sub(r"@@OUT (\S+)@@", lambda o: open(os.path.join(HERE, "out", o.group(1) + ".txt"), encoding="utf8").read().rstrip(), body)
        return '<pre class="out">' + html.escape(body.strip("\n")) + "</pre>"
    run = kind.startswith("run ")
    lang = kind[4:] if run else kind
    pre = '<pre class="code" data-lang="' + lang + '">' + html.escape(body.rstrip("\n")) + "</pre>"
    return '<div class="runbox">' + pre + '<button data-run>See it run</button></div>' if run else pre


ans = {}
for f in sorted(glob.glob(os.path.join(HERE, "*.txt"))):
    for sec in re.split(r"^=== ", open(f, encoding="utf8").read(), flags=re.M)[1:]:
        tag, body = sec.split("\n", 1)
        assert tag.strip() not in ans, "duplicate " + tag
        ans[tag.strip()] = re.sub(r"^```([^\n]*)\n(.*?)^```\s*$", block, body.strip(), flags=re.M | re.S)

# "@@SAME <tag>" = the question was set again; reuse that answer
for tag, body in ans.items():
    m = re.fullmatch(r"@@SAME (.+)", body.strip())
    if m:
        ans[tag] = '<p class="log">Same question as <b>' + m.group(1) + "</b>; the answer is repeated here.</p>" + ans[m.group(1)]

with open(os.path.join(HERE, "..", "answers.js"), "w", encoding="utf8") as fh:
    fh.write("/* generated by answers/build.py from answers/*.txt -- edit those, not this */\nvar ANS=" + json.dumps(ans, ensure_ascii=False).replace("</", "<\\/") + ";\n")
print(len(ans), "answers")

# ---- topic pages: chunks/*.txt -> ../chunks.js ----
# sections "=== 1.1", an optional first line "Q: tag, tag, ..." (questions on this topic), then the body
CH = os.path.join(HERE, "..", "chunks")
content = {}
for f in sorted(glob.glob(os.path.join(CH, "*.txt"))):
    for sec in re.split(r"^=== ", open(f, encoding="utf8").read(), flags=re.M)[1:]:
        no, body = sec.split("\n", 1)
        body = body.strip()
        qs = []
        if body.startswith("Q:"):
            line, body = (body.split("\n", 1) + [""])[:2]
            qs = [t.strip() for t in line[2:].split(",") if t.strip()]
            missing = [t for t in qs if t not in ans]
            assert not missing, (no, missing)
        content[no.strip()] = {"h": re.sub(r"^```([^\n]*)\n(.*?)^```\s*$", block, body.strip(), flags=re.M | re.S), "qs": qs}
with open(os.path.join(HERE, "..", "chunks.js"), "w", encoding="utf8") as fh:
    fh.write("/* generated by answers/build.py from chunks/*.txt -- edit those, not this */\nvar CONTENT=" + json.dumps(content, ensure_ascii=False).replace("</", "<\\/") + ";\n")
print(len(content), "topic pages")
