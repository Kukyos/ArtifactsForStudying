"""answers/*.txt -> ../answers.js  (run: python webtech/answers/build.py)

A file is sections headed "=== <question tag>" (tags match PYQ in index.html).
Prose is plain HTML. Code goes in fenced blocks:
  ```html / ```js / ```jsx / ```mongo / ```css   shown as code
  ```run html                                     shown as code + a live preview button
  ```out  with @@OUT name@@                       real captured output from out/name.txt
"""
import glob, html, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))


def block(m):
    kind, body = m.group(1).strip(), m.group(2)
    if kind == "out":
        body = re.sub(r"@@OUT (\S+)@@", lambda o: open(os.path.join(HERE, "out", o.group(1) + ".txt"), encoding="utf8").read().rstrip(), body)
        return '<pre class="out">' + html.escape(body.strip("\n")) + "</pre>"
    run = kind.startswith("run ")
    lang = kind[4:] if run else kind
    pre = '<pre class="code" data-lang="' + lang + '">' + html.escape(body.rstrip("\n")) + "</pre>"
    return '<div class="runbox">' + pre + '<button data-run>See it run</button></div>' if run else pre


ans = {}
for f in sorted(glob.glob(os.path.join(HERE, "*.txt"))):
    for sec in re.split(r"^=== ", open(f, encoding="utf8").read(), flags=re.M)[1:]:
        tag, body = sec.split("\n", 1)
        assert tag.strip() not in ans, "duplicate " + tag
        ans[tag.strip()] = re.sub(r"^```([^\n]*)\n(.*?)^```\s*$", block, body.strip(), flags=re.M | re.S)

with open(os.path.join(HERE, "..", "answers.js"), "w", encoding="utf8") as fh:
    fh.write("/* generated by answers/build.py from answers/*.txt -- edit those, not this */\nvar ANS=" + json.dumps(ans, ensure_ascii=False).replace("</", "<\\/") + ";\n")
print(len(ans), "answers")
